import { readFile, writeFile } from "node:fs/promises";
import { kebab } from "../src/foundations/kebab.ts";
import {
  borders,
  colors,
  darkColors,
  darkElevation,
  elevation,
  fontFamily,
  motion,
  opacity,
  radii,
  reducedMotion,
  sizing,
  spacing,
  typography,
} from "../src/foundations/tokens.ts";

const declarations = [];
const add = (name, value) => declarations.push(`  --${name}: ${value};`);

for (const [name, value] of Object.entries(colors)) {
  add(`color-pancake-${kebab(name)}`, value);
}
for (const value of [
  ...new Set([...Object.values(spacing), ...Object.values(sizing)]),
].sort((a, b) => a - b)) {
  add(`spacing-pancake-${value}`, `${value}px`);
}
for (const [name, value] of Object.entries(radii)) {
  add(
    `radius-pancake-${kebab(name.replace("radius", "")).replace(/^-/, "")}`,
    `${value}px`,
  );
}
add("font-pancake", fontFamily);
for (const [name, value] of Object.entries(typography)) {
  const token = `text-pancake-${kebab(name)}`;
  add(token, `${value.fontSize}px`);
  add(`${token}--line-height`, value.lineHeight);
  add(`${token}--font-weight`, value.fontWeight);
  add(`${token}--letter-spacing`, `${value.letterSpacing}px`);
}
for (const [name, value] of Object.entries(borders)) {
  add(`pancake-${kebab(name)}`, `${value}px`);
}
for (const [name, value] of Object.entries(opacity)) {
  add(`pancake-${kebab(name)}`, value);
}

const custom = (values, indent) =>
  Object.entries(values)
    .map(([name, value]) => `${indent}--pancake-${kebab(name)}: ${value};`)
    .join("\n");
const themedColors = Object.entries(darkColors).filter(
  ([name, value]) => colors[name] !== value,
);
const palette = (scheme, indent) =>
  [
    `${indent}color-scheme: ${scheme};`,
    custom(scheme === "dark" ? darkElevation : elevation, indent),
    ...themedColors.map(
      ([name, dark]) =>
        `${indent}--color-pancake-${kebab(name)}: ${scheme === "dark" ? dark : colors[name]};`,
    ),
  ].join("\n");
const themeRule = (theme, scheme, indent) =>
  `${indent}:root[data-pancake-theme="${theme}"],\n${indent}[data-pancake-theme="${theme}"] {\n${palette(scheme, `${indent}  `)}\n${indent}}`;

const output = `/* Generated by scripts/generate-theme.mjs. Edit src/foundations/tokens.ts. */
@theme static {
${declarations.join("\n")}
}

:root {
${custom(motion, "  ")}
${custom(elevation, "  ")}
}
@media (prefers-reduced-motion: reduce) {
  :root {
${custom(reducedMotion, "    ")}
  }
}
${themeRule("light", "light", "")}
${themeRule("dark", "dark", "")}
@media (prefers-color-scheme: light) {
${themeRule("system", "light", "  ")}
}
@media (prefers-color-scheme: dark) {
${themeRule("system", "dark", "  ")}
}
`;
const destination = new URL("../src/foundations/theme.css", import.meta.url);
if (process.argv.includes("--check")) {
  if ((await readFile(destination, "utf8")) !== output) {
    throw new Error("src/foundations/theme.css is stale. Run npm run tokens.");
  }
} else {
  await writeFile(destination, output);
}
