import { readFile, writeFile } from "node:fs/promises";
import {
  borders,
  colors,
  opacity,
  radii,
  sizing,
  spacing,
  typography,
} from "../src/foundations/tokens.ts";

const kebab = (value) =>
  value.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
const declarations = [];
const add = (name, value) => declarations.push(`  --${name}: ${value};`);

for (const [name, value] of Object.entries(colors)) {
  add(`color-pancake-${kebab(name)}`, value);
}
for (const value of [
  ...new Set([...Object.values(spacing), ...Object.values(sizing)]),
].sort((a, b) => a - b)) {
  add(`spacing-pancake-${value}`, `${value}px`);
}
for (const [name, value] of Object.entries(radii)) {
  add(
    `radius-pancake-${kebab(name.replace("radius", "")).replace(/^-/, "")}`,
    `${value}px`,
  );
}
add("font-pancake", "Inter, sans-serif");
for (const [name, value] of Object.entries(typography)) {
  const token = `text-pancake-${kebab(name)}`;
  add(token, `${value.fontSize}px`);
  add(`${token}--line-height`, value.lineHeight);
  add(`${token}--font-weight`, value.fontWeight);
  add(`${token}--letter-spacing`, `${value.letterSpacing}px`);
}
for (const [name, value] of Object.entries(borders)) {
  add(`pancake-${kebab(name)}`, `${value}px`);
}
for (const [name, value] of Object.entries(opacity)) {
  add(`pancake-${kebab(name)}`, value);
}

const output = `/* Generated by scripts/generate-theme.mjs. Edit src/foundations/tokens.ts. */\n@theme static {\n${declarations.join("\n")}\n}\n`;
const destination = new URL("../src/foundations/theme.css", import.meta.url);
if (process.argv.includes("--check")) {
  if ((await readFile(destination, "utf8")) !== output) {
    throw new Error("src/foundations/theme.css is stale. Run npm run tokens.");
  }
} else {
  await writeFile(destination, output);
}
